export function kicksFor(type, from, to) {
  const key = `${from}>${to}`;
  if (type === 'I') return KICKS_I[key] || [[0, 0]];
  if (type === 'O') return KICKS_O[key] || [[0, 0]];
  return KICKS_JLSTZ[key] || [[0, 0]];
}

/** Классический генератор «7-bag»: каждая семёрка содержит все 7 фигур. */
export function createBag() {
  let bag = [];
  return {
    next() {
      if (bag.length === 0) {
        bag = PIECE_ORDER.slice();
        for (let i = bag.length - 1; i > 0; i--) {
          const j = Math.floor(Math.random() * (i + 1));
          [bag[i], bag[j]] = [bag[j], bag[i]];
        }
      }
      return bag.pop();
    },
  };
}
