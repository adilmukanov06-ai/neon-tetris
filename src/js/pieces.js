/**
 * pieces.js — описание фигур, система координат и таблицы кик-оффсетов.
 *
 * Система координат (SRS, guideline-совместимая):
 *   • поле 10 x 20, x — вправо, y — вниз;
 *   • каждая фигура описана матрицей (сворачивается в бокс NxN);
 *   • центр вращения = центр бокса. Для 3x3 (J L S T Z) это клетка (1,1),
 *     для I (бокс 4x4) — точка (1.5, 1.5), для O (бокс 2x2) — (0.5, 0.5);
 *   • чтобы корректно хранить «половинные» центры, позиция фигуры и
 *     смещения клеток считаются в УДВОЕННЫХ единицах (double units).
 *     Например: 2 клетки = 4 double units.
 */

